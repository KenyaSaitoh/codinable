-- 社員と異動履歴のテーブル（起動のたびに作り直す）
-- 一括ドロップ（外部キー制約があるため、参照する側から先にドロップする）
DROP TABLE TRANSFER_HISTORY IF EXISTS;
DROP TABLE EMPLOYEE IF EXISTS;
DROP TABLE DEPARTMENT IF EXISTS;

-- 部署テーブル
CREATE TABLE DEPARTMENT (
DEPARTMENT_ID   INTEGER PRIMARY KEY,           -- 部署ID
DEPARTMENT_NAME VARCHAR(30) NOT NULL,          -- 部署名
LOCATION        VARCHAR(30)                    -- 所在地
);

-- 社員テーブル
CREATE TABLE EMPLOYEE (
EMPLOYEE_ID   INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 10017) PRIMARY KEY,  -- 社員ID
EMPLOYEE_NAME VARCHAR(30) NOT NULL,            -- 社員名
DEPARTMENT_ID INTEGER,                         -- 部署ID（外部キー。部署なしはNULL）
JOB_NAME      VARCHAR(20),                     -- 職種
SALARY        INTEGER,                         -- 給与
ENTRANCE_DATE DATE,                            -- 入社日
FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENT (DEPARTMENT_ID)
);

-- 異動履歴テーブル（非同期のリスナー TransferHistoryRecorder が書き込む）
CREATE TABLE TRANSFER_HISTORY (
HISTORY_ID         INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY, -- 履歴ID
EMPLOYEE_ID        INTEGER NOT NULL,           -- 社員ID
FROM_DEPARTMENT_ID INTEGER,                    -- 異動前の部署ID（部署なしはNULL）
TO_DEPARTMENT_ID   INTEGER NOT NULL,           -- 異動後の部署ID
OCCURRED_AT        TIMESTAMP NOT NULL,         -- 異動を登録した日時
FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE (EMPLOYEE_ID)
);
