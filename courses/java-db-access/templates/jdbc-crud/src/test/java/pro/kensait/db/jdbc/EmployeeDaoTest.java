package pro.kensait.db.jdbc;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.math.BigDecimal;
import java.sql.SQLException;
import java.util.List;
import org.hsqldb.jdbc.JDBCDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

/*
 * 社員daoのテスト
 */
class EmployeeDaoTest {
    private EmployeeDao dao;

    // 各テストケースで共通的な前処理
    @BeforeEach
    void setUp() throws Exception {
        JDBCDataSource dataSource = new JDBCDataSource();
        dataSource.setUrl("jdbc:hsqldb:mem:crud_course");
        dataSource.setUser("SA");
        dataSource.setPassword("");
        // 破壊的な初期化は、テスト専用インメモリDBのセットアップに限定する
        try (var connection = dataSource.getConnection();
                var statement = connection.createStatement()) {
            statement.executeUpdate("DROP TABLE EMPLOYEE IF EXISTS");
            // EMPLOYEE_IDは自動採番（指定しなければ10017から採番。指定すればその値）、
            // VERSIONは楽観ロック用のバージョン番号（登録時は0）
            statement.executeUpdate("CREATE TABLE EMPLOYEE ("
                    + "EMPLOYEE_ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 10017) "
                    + "PRIMARY KEY, "
                    + "DEPARTMENT_ID INTEGER, EMPLOYEE_NAME VARCHAR(100) NOT NULL, "
                    + "SALARY DECIMAL(12, 2) NOT NULL, "
                    + "VERSION INTEGER DEFAULT 0 NOT NULL)");
            // 初期データ16人（部署ID 1=PLANNING / 2=HR / 3=SALES / 4=PRODUCT、Victorは未所属）
            statement.executeUpdate("INSERT INTO EMPLOYEE "
                    + "(EMPLOYEE_ID, DEPARTMENT_ID, EMPLOYEE_NAME, SALARY) VALUES "
                    + "(10001, 3, 'Alice', 500000), "
                    + "(10002, 1, 'Bob', 450000), "
                    + "(10003, 2, 'Carol', 350000), "
                    + "(10004, 3, 'Dave', 400000), "
                    + "(10005, 3, 'Ellen', 300000), "
                    + "(10006, 1, 'Frank', 250000), "
                    + "(10007, 4, 'Ivan', 480000), "
                    + "(10008, 2, 'Justin', 460000), "
                    + "(10009, 4, 'Mallory', 420000), "
                    + "(10010, 3, 'Matilda', 280000), "
                    + "(10011, 4, 'Oscar', 320000), "
                    + "(10012, 4, 'Pat', 240000), "
                    + "(10013, 3, 'Peggy', 270000), "
                    + "(10014, NULL, 'Victor', 220000), "
                    + "(10015, 1, 'Steve', 380000), "
                    + "(10016, 4, 'Trent', 310000)");
        }
        dao = new EmployeeDao(dataSource);
    }

    // 「バインドパラメータによるCRUD」の検証
    @Test
    void performsCrudWithBoundParameters() throws Exception {
        Employee original = new Employee(10017, 3, "Walter", new BigDecimal("230000.00"));
        assertEquals(1, dao.insert(original));
        assertEquals(original, dao.findById(10017).orElseThrow());

        Employee changed = new Employee(10017, 4, "Walter", new BigDecimal("260000.00"));
        assertEquals(1, dao.update(changed));
        assertEquals(changed, dao.findById(10017).orElseThrow());

        assertEquals(1, dao.delete(10017));
        assertTrue(dao.findById(10017).isEmpty());
    }

    // 「部署を条件にした検索・一括更新・一括削除」の検証
    @Test
    void handlesDepartmentWideSearchUpdateAndDelete() throws Exception {
        List<Employee> sales = dao.findByDepartmentId(3);
        assertEquals(List.of(10001, 10004, 10005, 10010, 10013),
                sales.stream().map(Employee::id).toList());

        assertEquals(3, dao.raiseSalaryByDepartmentId(1, new BigDecimal("10000")));
        assertEquals(new BigDecimal("460000.00"), dao.findById(10002).orElseThrow().salary());
        assertEquals(new BigDecimal("500000.00"), dao.findById(10001).orElseThrow().salary());

        assertEquals(2, dao.deleteByDepartmentId(2));
        assertTrue(dao.findByDepartmentId(2).isEmpty());
        assertEquals(0, dao.deleteByDepartmentId(2));
    }

    // 「自動採番キーの取得」の検証
    @Test
    void insertAndReturnId() throws Exception {
        // 社員番号を渡さずに登録すると、DBが採番した10017が返る
        Employee walter = new Employee(0, 3, "Walter", new BigDecimal("230000.00"));
        int generatedId = dao.insertAndReturnId(walter);
        assertEquals(10017, generatedId);

        Employee saved = dao.findById(10017).orElseThrow();
        assertEquals("Walter", saved.name());
        assertEquals(new BigDecimal("230000.00"), saved.salary());
    }

    // 「バージョン番号による楽観ロック」の検証
    @Test
    void updateSalaryWithVersion() throws Exception {
        // 登録直後のVERSIONは0
        assertEquals(0, dao.findVersionById(10004));

        // VERSION=0を期待して更新 → 1件更新され、VERSIONは1に進む
        assertEquals(1, dao.updateSalaryWithVersion(10004, new BigDecimal("410000"), 0));
        assertEquals(new BigDecimal("410000.00"), dao.findById(10004).orElseThrow().salary());
        assertEquals(1, dao.findVersionById(10004));

        // 同じVERSION=0を期待してもう一度更新 → 先の更新でVERSIONが進んでいるので0件（給与は変わらない）
        assertEquals(0, dao.updateSalaryWithVersion(10004, new BigDecimal("420000"), 0));
        assertEquals(new BigDecimal("410000.00"), dao.findById(10004).orElseThrow().salary());
        assertEquals(1, dao.findVersionById(10004));
    }

    // 「氏名内のSQL構文のデータ扱い」の検証
    @Test
    void treatsSqlSyntaxInNameAsData() throws Exception {
        Employee employee = new Employee(10017, 3, "O'Brien'); DROP TABLE EMPLOYEE; --",
                new BigDecimal("420000.00"));
        assertEquals(1, dao.insert(employee));
        assertEquals(employee, dao.findById(10017).orElseThrow());
    }

    // 「他社員を変更しない未存在行の通知」の検証
    @Test
    void reportsMissingRowsWithoutChangingOtherEmployees() throws Exception {
        assertTrue(dao.findById(999).isEmpty());
        assertEquals(0, dao.update(new Employee(999, 3, "不在", BigDecimal.ZERO)));
        assertEquals(0, dao.delete(999));
    }

    // 「確定済み社員を上書きしないID重複エラー」の検証
    @Test
    void duplicateIdFailsWithoutOverwritingCommittedEmployee() throws Exception {
        Employee original = new Employee(10017, 3, "Walter", new BigDecimal("230000.00"));
        dao.insert(original);
        assertThrows(SQLException.class,
                () -> dao.insert(new Employee(10017, 4, "別の社員", BigDecimal.ZERO)));
        assertEquals(original, dao.findById(10017).orElseThrow());
    }
}
