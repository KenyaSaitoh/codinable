CREATE TABLE DEPARTMENT (
  DEPARTMENT_ID   INTEGER     PRIMARY KEY,
  DEPARTMENT_NAME VARCHAR(30) NOT NULL,
  LOCATION        VARCHAR(50) NOT NULL
);

CREATE TABLE JOB (
  JOB_ID   INTEGER     PRIMARY KEY,
  JOB_NAME VARCHAR(30) NOT NULL,
  GRADE    INTEGER     NOT NULL
);

CREATE TABLE EMPLOYEE (
  EMPLOYEE_ID   INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
  EMPLOYEE_CODE VARCHAR(8)  NOT NULL,
  EMPLOYEE_NAME VARCHAR(30) NOT NULL,
  DEPARTMENT_ID INTEGER     NOT NULL REFERENCES DEPARTMENT(DEPARTMENT_ID),
  JOB_ID        INTEGER     NOT NULL REFERENCES JOB(JOB_ID),
  SALARY        INTEGER     NOT NULL,
  ENTRANCE_DATE DATE        NOT NULL,
  STATUS        VARCHAR(10) DEFAULT 'active' NOT NULL,
  VERSION       INTEGER     DEFAULT 0 NOT NULL
);

CREATE INDEX IDX_EMPLOYEE_NAME ON EMPLOYEE(EMPLOYEE_NAME);
CREATE INDEX IDX_EMPLOYEE_SALARY ON EMPLOYEE(SALARY);
